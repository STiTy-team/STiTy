#!/bin/bash
# prefix16: prefix labels (design docs/superpowers/specs/2026-11-14-prefix16-prefix-labels-design.md).
#   label_prefix (labeler sees only the heard prefix + committed text; waits from regret) -> judge1
#   -> relabel the judge failures with the reviewer notes -> judge2 -> compose -> completeness gate + wait labels
#   + hygiene table (with est_lag_s) -> auto_go [GO] -> rows -> SFT -> merge -> bench (3 jobs, manager queue, run-now)
#   -> post (northstar en rescore + COMET, lookahead for all).
# Idempotent by file existence; rerun the same command to resume. Markers P16 MARK/FAIL/SMOKE_READY/STATS_READY/SFT_READY/DONE/EXIT.
# Env: OUT (label dir), SENTS (sentence manifest), SMOKE=1 (pilot sentences, budget 3, stop after the hygiene table),
#      BENCH=0 skips the bench, STOP_AFTER_ROWS=1 stops after the rows, MACHINE (queue machine, default gpu2),
#      BRANCH (job branch, default exp/schedule-labels), MANAGER (default localhost:29140).
# Do not edit this file while it runs (bash reads it piecewise): kill -> edit -> rerun.
cd "$(git -C "$(dirname "${BASH_SOURCE[0]}")" rev-parse --show-toplevel)" || exit 1  # locate the repo from this file, not the caller's cwd
set -o pipefail
trap 'echo "P16_EXIT $(date "+%F %T")"' EXIT
[ -f .env ] && { set -a; . ./.env; set +a; }
export PATH=$HOME/.local/bin:$PATH
PY=.venv/bin/python; CPY=.venv-tpm/bin/python
OUT=${OUT:-models/zprobe/data/prefix16}; LOG=models/zprobe/logs; mkdir -p $LOG $OUT
D14=models/zprobe/data/prefix14
SENTS=${SENTS:-$D14/sentences.jsonl}; HY=$D14/hy_prefixes.jsonl; WT=$D14/word_times.jsonl
LABEL_MODEL=${LABEL_MODEL:-gpt-6-luna}; LABEL_BUDGET=${LABEL_BUDGET:-60}; JUDGE_BUDGET=${JUDGE_BUDGET:-10}; LABEL_WORKERS=${LABEL_WORKERS:-32}
if [ "${SMOKE:-0}" = 1 ]; then SENTS=${SENTS_SMOKE:-$OUT/pilot_sentences.jsonl}; LABEL_BUDGET=3; JUDGE_BUDGET=1; fi
RULES=core/research/zprobe/labels/prompts/prefix_rules_v1.txt
L=core/research/zprobe/labels
S1=$OUT/schedule_${LABEL_MODEL}.jsonl; J1=$OUT/schedule.judge1.jsonl; S2=$OUT/schedule.retry.jsonl; J2=$OUT/schedule.retry.judge2.jsonl
SJ=$OUT/schedule.judged.jsonl; RESCUE=$OUT/rescue.jsonl; GATED=$OUT/schedule.gated.jsonl
MACHINE=${MACHINE:-gpu2}; BRANCH=${BRANCH:-exp/schedule-labels}; MANAGER=${MANAGER:-localhost:29140}
PIPE=brig.koen+prefix16-lidreset; DSNS=${DSNS:-"fleurs_en-ko_vol23 fleurs_ko-en_vol23 northstar_ko+en-ko"}

roomy() { local ok=0; while [ $ok -lt 3 ]; do
  if [ "$(nvidia-smi --query-gpu=memory.free --format=csv,noheader,nounits | head -1)" -ge "$1" ]; then ok=$((ok + 1)); else ok=0; fi
  [ $ok -lt 3 ] && sleep 60; done; }
stage() { echo "$(date '+%F %T') P16 MARK $*"; df -h / | tail -1 | awk '{print "  disk free " $4}'; }
spent() { $PY -c "
import json, os
t = 0.0
for p in ['$S1.usage.jsonl', '$J1.usage.jsonl', '$S2.usage.jsonl', '$J2.usage.jsonl']:
    if not os.path.exists(p): continue
    for l in open(p, encoding='utf-8'):
        try: t += json.loads(l)['est_usd']
        except Exception: pass
print(round(t, 2))"; }
label() {  # $@ extra args; exit 3 = API errors on >1% of rows -> one more pass after 10 min
  PYTHONPATH=. $PY -u $L/label_prefix.py --sentences $SENTS --model $LABEL_MODEL --reasoning low \
    --workers $LABEL_WORKERS --budget $LABEL_BUDGET --rules $RULES "$@"; local rc=$?
  if [ $rc -eq 3 ]; then echo "  label pass hit API errors; retrying the ERROR rows in 10 min"; sleep 600
    PYTHONPATH=. $PY -u $L/label_prefix.py --sentences $SENTS --model $LABEL_MODEL --reasoning low \
      --workers $LABEL_WORKERS --budget $LABEL_BUDGET --rules $RULES "$@"; rc=$?; fi
  return $rc; }
judge() {  # exit 3 = API errors on >1% -> one more pass after 10 min; exit 2 = budget stop (fails the stage)
  PYTHONPATH=. $PY -u $L/judge_schedule.py --schedule "$1" --sentences $SENTS --model $LABEL_MODEL --reasoning low \
    --workers $LABEL_WORKERS --budget $JUDGE_BUDGET --out "$2"; local rc=$?
  if [ $rc -eq 3 ]; then echo "  judge hit API errors; retrying the ERROR rows in 10 min"; sleep 600
    PYTHONPATH=. $PY -u $L/judge_schedule.py --schedule "$1" --sentences $SENTS --model $LABEL_MODEL --reasoning low \
      --workers $LABEL_WORKERS --budget $JUDGE_BUDGET --out "$2"; rc=$?; fi
  return $rc; }

stage "label ($LABEL_MODEL, prefix rules v1, budget $LABEL_BUDGET, sentences $SENTS)"
[ -f $OUT/label.done ] || { label --out $S1 && touch $OUT/label.done || { echo P16_FAIL label; exit 1; }; }
echo "  labeled: $(wc -l < $S1), failed: $(wc -l < $S1.fail.jsonl 2>/dev/null || echo 0), spent \$$(spent)"

stage "judge 1"
[ -f $OUT/judge1.done ] || { judge $S1 $J1 && touch $OUT/judge1.done || { echo P16_FAIL judge1; exit 1; }; }
$PY -c "
import json
j = [json.loads(l) for l in open('$J1', encoding='utf-8') if l.strip()]
bad = [x['sid'] for x in j if not x['pass']]
open('$OUT/judge1.fail_sids.txt', 'w').write('\n'.join(bad) + ('\n' if bad else ''))
print(f'  judged {len(j)}, defects {len(bad)}')"

stage "relabel the judge failures"
if [ ! -f $OUT/relabel.done ]; then
  if [ -s $OUT/judge1.fail_sids.txt ]; then
    label --only-sids $OUT/judge1.fail_sids.txt --notes $J1 --out $S2 || { echo P16_FAIL relabel; exit 1; }
  else : > $S2; fi
  touch $OUT/relabel.done
fi

stage "judge 2"
if [ ! -f $OUT/judge2.done ]; then
  if [ -s $S2 ]; then judge $S2 $J2 || { echo P16_FAIL judge2; exit 1; }; else : > $J2; fi
  touch $OUT/judge2.done
fi
echo "  spent so far \$$(spent)"

stage "compose"
PYTHONPATH=. $PY $L/compose_judged.py --s1 $S1 --j1 $J1 --s2 $S2 --j2 $J2 --fail1 $S1.fail.jsonl --fail2 $S2.fail.jsonl \
  --sentences $SENTS --out $SJ --out-rescue $RESCUE || { echo P16_FAIL compose; exit 1; }

stage "completeness gate + wait labels + hygiene (with est_lag_s)"
OLD=""; [ -f models/zprobe/data/prefix13/aligned.jsonl ] && OLD="--old models/zprobe/data/prefix13/aligned.jsonl"
if [ ! -f $OUT/stats.done ]; then
  rm -f $OUT/GO
  roomy 6000
  if ! { PYTHONPATH=. $CPY -u $L/schedule_stats.py --schedule $SJ --sentences $SENTS --hy $HY --word-times $WT \
      $OLD --rescue $RESCUE --judge $J1 \
      --out-gated ${GATED}.tmp --out-dropped $OUT/dropped.jsonl 2>&1 | tee $LOG/prefix16_stats.log; }; then
    echo P16_FAIL stats; exit 1
  fi
  mv ${GATED}.tmp $GATED && touch $OUT/stats.done
fi
echo "P16_STATS_READY $(date '+%F %T') - $LOG/prefix16_stats.log"
if [ "${SMOKE:-0}" = 1 ]; then
  PYTHONPATH=. $PY $L/auto_go.py --gated $GATED --labeled $S1 --sentences $SENTS --min-kept 1 --min-kept-share 0 \
    --empty-min 0.05 2>&1 | tee -a $LOG/prefix16_stats.log
  echo "P16_SMOKE_READY $(date '+%F %T') - spent \$$(spent)"; exit 0
fi
if [ ! -f $OUT/GO ]; then
  PYTHONPATH=. $PY $L/auto_go.py --gated $GATED --labeled $S1 --sentences $SENTS --empty-min 0.05 2>&1 | tee -a $LOG/prefix16_stats.log
  [ ${PIPESTATUS[0]} -eq 0 ] && touch $OUT/GO || { echo "P16_FAIL hygiene - review $LOG/prefix16_stats.log; to override: touch $OUT/GO and rerun"; exit 1; }
fi

stage "training rows"
[ -f models/zprobe/data/train_prefix16.jsonl ] || $PY $L/build_prefix14.py \
  --schedule $GATED --sentences $SENTS --word-times $WT \
  --sil-wav models/zprobe/data/silence_tail_4s.wav --out models/zprobe/data/train_prefix16.jsonl \
  --val-out models/zprobe/data/val_prefix16.jsonl --rows-per-rec 5 --catchup-per-rec 2 --val-cap 1500 \
  --sil-cap 800 --seg-cap 2500 --reset-rows 3000 --seed 16 || { echo P16_FAIL rows; exit 1; }
echo "  train rows: $(wc -l < models/zprobe/data/train_prefix16.jsonl), val rows: $(wc -l < models/zprobe/data/val_prefix16.jsonl)"
[ "${STOP_AFTER_ROWS:-0}" = 1 ] && { echo "P16_ROWS_READY $(date '+%F %T') - STOP_AFTER_ROWS=1"; exit 0; }

stage "sft"
sft() { $PY -u Qwen3-ASR/finetuning/qwen3_asr_sft.py \
  --model_path models/Qwen3-ASR-1.7B-koen-seg-mix-merged \
  --train_file models/zprobe/data/train_prefix16.jsonl --eval_file models/zprobe/data/val_prefix16.jsonl \
  --output_dir models/zprobe/adapters/prefix16 --use_lora 1 --no_seg 1 --load_best 1 --lazy_features 1 \
  --lora_r 64 --lora_alpha 128 --lora_dropout 0.05 --lora_targets q_proj,k_proj,v_proj,o_proj \
  --lr 1e-4 --epochs 1 --batch_size 2 --grad_acc 8 --save_steps 200 --save_total_limit 2 --resume 1 "$@"; }
if [ ! -f models/zprobe/adapters/prefix16/final/adapter_model.safetensors ]; then
  roomy 20000
  sft --gradient_checkpointing 0 > $LOG/sft_prefix16.log 2>&1 || sft --gradient_checkpointing 1 >> $LOG/sft_prefix16.log 2>&1 \
    || { echo P16_FAIL sft; tail -5 $LOG/sft_prefix16.log; exit 1; }
fi
grep -oE "'eval_loss': [0-9.]+|'eval_cer': [0-9.]+" $LOG/sft_prefix16.log | tail -2

stage "merge"
[ -d models/zprobe/merged/prefix16_full ] || PYTHONPATH=Qwen3-ASR $PY core/research/zprobe/train/merge_adapter.py \
  --base models/Qwen3-ASR-1.7B-koen-seg-mix-merged --adapter models/zprobe/adapters/prefix16/final \
  --out models/zprobe/merged/prefix16_full || { echo P16_FAIL merge; exit 1; }
echo "P16_SFT_READY $(date '+%F %T')"

submit() {  # $1 dataset -> job id on stdout (empty on failure); run-now
  CFG=$PIPE DSN=$1 BR=$BRANCH python3 - <<'PYEOF' | curl -s -XPOST http://$MANAGER/api/machines/$MACHINE/jobs -H 'Content-Type: application/json' -d @- | python3 -c "import json,sys; d=json.load(sys.stdin); x=d.get('data') or {}; print(x.get('id') or ''); sys.stderr.write('P16 JOB %s %s %s\n' % (d.get('ok'), x.get('id'), str(d.get('error',''))[:200]))"
import json, os, pathlib
c, d = os.environ["CFG"], os.environ["DSN"]
print(json.dumps({"branch": os.environ["BR"], "pipeline": {"name": c, "yaml": pathlib.Path(f"configs/pipelines/{c}.yml").read_text()},
                  "dataset": {"name": d, "yaml": pathlib.Path(f"configs/datasets/{d}.yml").read_text()}}))
PYEOF
}
wait_job() {  # $1 job id: poll until it leaves the queue
  local n=0
  while :; do
    curl -s --max-time 20 http://$MANAGER/api/machines | JID=$1 M=$MACHINE python3 -c "
import json, os, sys
try:
    d = json.load(sys.stdin)
    jobs = [x for m in d['machines'] if m['host'] == os.environ['M'] for x in m['jobs']]
    sys.exit(0 if any(str(x['id']) == os.environ['JID'] for x in jobs) else 1)
except Exception:
    sys.exit(2)
"
    rc=$?; [ $rc -eq 1 ] && break
    n=$((n + 1)); [ $((n % 10)) -eq 0 ] && echo "$(date '+%F %T') P16 waiting for bench job $1 (rc=$rc)"; sleep 60
  done; }

stage "bench ($MACHINE queue via manager $MANAGER): $DSNS"
if [ "${BENCH:-1}" = 0 ]; then echo "  BENCH=0: skipping the bench"
else
  for DSN in $DSNS; do
    JF=$OUT/bench.$DSN.job
    if [ -f $JF ]; then JOB=$(cat $JF); echo "  reuse bench job $JOB ($DSN)"
    else JOB=$(submit $DSN); [ -n "$JOB" ] || { echo "P16_FAIL bench-submit $DSN"; exit 1; }; echo "$JOB" > $JF
      curl -s -XPOST http://$MANAGER/api/machines/$MACHINE/jobs/$JOB/run-now -H 'Content-Type: application/json' -d '{}' > /dev/null; fi
    wait_job $JOB
  done
  stage "post: pull runs, northstar en rescore + COMET, lookahead"
  for DSN in $DSNS; do
    V=$DSN; grep -q "version: 2" configs/datasets/$DSN.yml && V="$DSN@v2"
    RUN="bench/runs/$V/$PIPE"; WRUN="$HOME/.cache/stity/worktree/$RUN"
    [ -f $RUN/summary.json ] || { [ -d "$WRUN" ] && mkdir -p "$(dirname $RUN)" && cp -r "$WRUN" "$RUN"; }
    [ -f $RUN/summary.json ] || { echo "  $RUN not found locally - pull it from the manager (Runs page) and rerun"; continue; }
    T=$($PY -c "import yaml; print(yaml.safe_load(open('configs/datasets/$DSN.yml'))['target'])")
    PYTHONPATH=. $PY core/research/zprobe/eval/lookahead_rate.py --run-dir $RUN --target $T --grace 2.0 2>&1 | grep -E "LOOKAHEAD"
    $PY -c "
import json; m=json.load(open('$RUN/summary.json'))['metrics']
print('$V', 'COMET', round(m.get('comet') or 0,4), 'YAAL', round(m.get('yaal_ms') or m.get('longyaal_ms') or 0), 'lid', round((m.get('commit_reasons') or {}).get('lid',0),3))"
  done
  EN="bench/runs/northstar_ko+en-en@v2/$PIPE"
  if [ -f bench/runs/northstar_ko+en-ko@v2/$PIPE/summary.json ] && [ ! -f $EN/comet_scores.jsonl ]; then
    uv run --project bench python scripts/brig_rescore.py --pipeline $PIPE --src-dataset northstar_ko+en-ko --dst-dataset northstar_ko+en-en \
      && uv run --project bench/metrics/comet python -m bench.metrics.comet --run-dir $EN 2>&1 | grep -E '"comet"'
    PYTHONPATH=. $PY core/research/zprobe/eval/lookahead_rate.py --run-dir $EN --target en --grace 2.0 2>&1 | grep -E "LOOKAHEAD"
  fi
fi
echo "P16_DONE $(date '+%F %T') - spent \$$(spent)"
